  update_date date NOT NULL DEFAULT current_date CHECK (update_date <= current_date),
  note text NOT NULL CHECK (length(trim(note)) BETWEEN 3 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.pt_daily_updates ENABLE ROW LEVEL SECURITY;
