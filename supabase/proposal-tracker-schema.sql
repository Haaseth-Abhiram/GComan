CREATE TRIGGER pt_user_permissions_audit AFTER INSERT OR UPDATE OR DELETE ON public.pt_user_permissions FOR EACH ROW EXECUTE FUNCTION public.pt_audit();
CREATE TRIGGER pt_rfq_costing_audit AFTER INSERT OR UPDATE OR DELETE ON public.pt_rfq_costing FOR EACH ROW EXECUTE FUNCTION public.pt_audit();
