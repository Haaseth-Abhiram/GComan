CREATE TYPE public.rfq_status AS ENUM ('New','Assigned','In Progress','Under Review','Returned','Approved','Submitted','Won','Lost');
CREATE TYPE public.priority_level AS ENUM ('High','Medium','Low');

CREATE TABLE public.pt_employees (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pt_rfqs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ref text NOT NULL UNIQUE,                       -- GC-RFQ-YYYY-NNN, generated by trigger
  customer_ref text UNIQUE,
  customer_name text NOT NULL CHECK (length(trim(customer_name)) >= 2),
  customer_contact text, customer_email text, customer_phone text,
  project text NOT NULL CHECK (length(trim(project)) >= 3),
  received_date date NOT NULL,
  deadline date NOT NULL,
  priority public.priority_level NOT NULL DEFAULT 'Medium',
  target_date date,
  primary_engineer_id uuid REFERENCES public.pt_employees(user_id),
  status public.rfq_status NOT NULL DEFAULT 'New',
  progress int NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  pending_actions text NOT NULL DEFAULT '',
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (deadline >= received_date)
);

CREATE TABLE public.pt_rfq_supporting (
  rfq_id uuid REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  engineer_id uuid REFERENCES public.pt_employees(user_id),
  PRIMARY KEY (rfq_id, engineer_id)
);

CREATE TABLE public.pt_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  rfq_id uuid NOT NULL REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  title text NOT NULL, description text NOT NULL DEFAULT '',
  owner_id uuid NOT NULL REFERENCES public.pt_employees(user_id),
  start_date date NOT NULL, due_date date NOT NULL,
  priority public.priority_level NOT NULL DEFAULT 'Medium',
  status text NOT NULL DEFAULT 'Not Started' CHECK (status IN ('Not Started','In Progress','Blocked','Completed')),
  completion int NOT NULL DEFAULT 0 CHECK (completion BETWEEN 0 AND 100),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (due_date >= start_date)
);

CREATE TABLE public.pt_followups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  rfq_id uuid NOT NULL REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('Customer Clarification','Vendor Response','Next Action','Reminder')),
  note text NOT NULL, due_date date NOT NULL, done boolean NOT NULL DEFAULT false,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pt_documents (                -- file bytes live in a Storage bucket, not the row
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  rfq_id uuid NOT NULL REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  category text NOT NULL CHECK (category IN ('RFQ','Specification','BOQ','Vendor Offer','Submitted Proposal')),
  file_name text NOT NULL, storage_path text NOT NULL UNIQUE, size_bytes bigint, mime text,
  uploaded_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pt_approvals (                -- append-only history
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  rfq_id uuid NOT NULL REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  action text NOT NULL CHECK (action IN ('Sent for Review','Approved','Returned')),
  reviewer_id uuid NOT NULL REFERENCES auth.users(id),
  comment text NOT NULL DEFAULT '', at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pt_submissions (              -- append-only history
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  rfq_id uuid NOT NULL REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  submitted_date date NOT NULL, revision int NOT NULL, reference text NOT NULL UNIQUE,
  notes text NOT NULL DEFAULT '', supporting_docs text[] NOT NULL DEFAULT '{}',
  recorded_by uuid REFERENCES auth.users(id), created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (rfq_id, revision)
);

CREATE TABLE public.pt_notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  text text NOT NULL, rfq_id uuid REFERENCES public.pt_rfqs(id) ON DELETE CASCADE,
  read_at timestamptz, created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pt_audit_log (
  id bigserial PRIMARY KEY, table_name text NOT NULL, row_id uuid, action text NOT NULL,
  actor uuid, old_data jsonb, new_data jsonb, at timestamptz NOT NULL DEFAULT now()
);

-- updated_at + audit triggers ------------------------------------------------
CREATE OR REPLACE FUNCTION public.pt_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END $$;

CREATE OR REPLACE FUNCTION public.pt_audit() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.pt_audit_log(table_name,row_id,action,actor,old_data,new_data)
  VALUES (TG_TABLE_NAME, COALESCE((to_jsonb(NEW)->>'id'),(to_jsonb(OLD)->>'id'))::uuid, TG_OP, auth.uid(),
          CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END, CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END);
  RETURN COALESCE(NEW, OLD);
END $$;

-- unique, race-safe RFQ reference
CREATE SEQUENCE public.pt_rfq_seq;
CREATE OR REPLACE FUNCTION public.pt_rfq_ref() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.ref IS NULL OR NEW.ref = '' THEN
    NEW.ref := 'GC-RFQ-' || to_char(now(),'YYYY') || '-' || lpad(nextval('public.pt_rfq_seq')::text, 3, '0');
  END IF; RETURN NEW;
END $$;
ALTER TABLE public.pt_rfqs ALTER COLUMN ref DROP NOT NULL;  -- filled by trigger; UNIQUE still enforced
CREATE TRIGGER pt_rfqs_ref BEFORE INSERT ON public.pt_rfqs FOR EACH ROW EXECUTE FUNCTION public.pt_rfq_ref();

DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['pt_rfqs','pt_tasks','pt_followups'] LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.pt_touch()', t||'_touch', t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['pt_rfqs','pt_tasks','pt_followups','pt_documents','pt_approvals','pt_submissions'] LOOP
    EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.pt_audit()', t||'_audit', t);
  END LOOP;
END $$;

-- Row-level security (the real permission enforcement) -------------------------
-- Helper: admin. Uses the existing has_role() (SECURITY DEFINER).
CREATE OR REPLACE FUNCTION public.pt_is_elevated() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.has_role(auth.uid(),'admin')
$$;
CREATE OR REPLACE FUNCTION public.pt_can_see(_rfq uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.pt_is_elevated()
      OR EXISTS (SELECT 1 FROM public.pt_rfqs r WHERE r.id=_rfq AND (r.primary_engineer_id = auth.uid() OR r.created_by = auth.uid()))
      OR EXISTS (SELECT 1 FROM public.pt_rfq_supporting s WHERE s.rfq_id=_rfq AND s.engineer_id = auth.uid())
$$;
CREATE OR REPLACE FUNCTION public.pt_is_primary(_rfq uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.pt_is_elevated()
      OR EXISTS (SELECT 1 FROM public.pt_rfqs r WHERE r.id=_rfq AND r.primary_engineer_id = auth.uid())
$$;

-- Grantable permissions (admin-managed). Role is necessary but never sufficient for approval/costing.
CREATE TABLE public.pt_user_permissions (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  permission text NOT NULL CHECK (permission IN ('proposal.approve','proposal.view_commercial_costing','rfq.create','report.export_limited')),
  granted_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, permission)
);
-- Eligibility by role, mirroring PERMISSION_INFO in src/lib/permissions.ts:
--   proposal.approve                 -> admin
--   proposal.view_commercial_costing -> admin, engineer
--   rfq.create / report.export_limited -> engineer (admin has them by role)
CREATE OR REPLACE FUNCTION public.pt_has_permission(_perm text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.pt_user_permissions p
    WHERE p.user_id = auth.uid() AND p.permission = _perm
      AND CASE _perm
        WHEN 'proposal.approve' THEN public.has_role(auth.uid(),'admin')
        WHEN 'proposal.view_commercial_costing' THEN true
        ELSE public.has_role(auth.uid(),'engineer')
      END)
$$;

